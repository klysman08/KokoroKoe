#[test]
fn main_capability_grants_only_expected_product_commands() {
    let capability: serde_json::Value =
        serde_json::from_str(include_str!("../capabilities/main.json"))
            .expect("main capability should contain valid JSON");

    assert_eq!(capability["windows"], serde_json::json!(["main"]));
    assert_eq!(
        capability["permissions"],
        serde_json::json!([
            "core:event:allow-listen",
            "core:event:allow-unlisten",
            "allow-get-settings",
            "allow-update-settings",
            "allow-choose-workspace",
            "allow-open-workspace-folder",
            "allow-get-openrouter-credential-status",
            "allow-set-openrouter-api-key",
            "allow-delete-openrouter-api-key",
            "allow-validate-openrouter-api-key",
            "allow-list-openrouter-models",
            "allow-list-projects",
            "allow-get-project",
            "allow-create-project",
            "allow-update-project",
            "allow-list-sessions",
            "allow-get-session",
            "allow-create-session",
            "allow-update-session",
            "allow-start-session",
            "allow-pause-session",
            "allow-resume-session",
            "allow-stop-session",
            "allow-get-transcript-page",
            "allow-search-transcript",
            "allow-ask-manual-question",
            "allow-generate-recent-insights",
            "allow-get-session-summary",
            "allow-generate-session-summary",
            "allow-list-audio-devices",
            "allow-start-audio-device-test",
            "allow-stop-audio-device-test",
            "allow-list-transcription-models",
            "allow-download-transcription-model",
            "allow-cancel-model-download",
            "allow-resume-model-download",
            "allow-delete-transcription-model",
            "allow-set-default-transcription-model",
            "allow-start-live-transcription",
            "allow-get-live-transcription-status",
            "allow-stop-live-transcription"
        ])
    );
    assert!(capability.get("remote").is_none());
    let serialized = capability.to_string();
    for forbidden in [
        "core:default",
        "dialog:",
        "fs:",
        "http:",
        "shell:",
        "process:",
    ] {
        assert!(!serialized.contains(forbidden));
    }
}

#[test]
fn main_capability_grants_only_frontend_event_subscription_permissions() {
    let capability: serde_json::Value =
        serde_json::from_str(include_str!("../capabilities/main.json"))
            .expect("main capability should contain valid JSON");
    let core_permissions = capability["permissions"]
        .as_array()
        .expect("permissions should be an array")
        .iter()
        .filter_map(serde_json::Value::as_str)
        .filter(|permission| permission.starts_with("core:"))
        .collect::<Vec<_>>();

    assert_eq!(
        core_permissions,
        ["core:event:allow-listen", "core:event:allow-unlisten"]
    );
}

#[test]
fn tauri_configuration_enables_only_the_main_capability() {
    let configuration: serde_json::Value = serde_json::from_str(include_str!("../tauri.conf.json"))
        .expect("Tauri configuration should contain valid JSON");

    assert_eq!(
        configuration["app"]["security"]["capabilities"],
        serde_json::json!(["main"])
    );
}

